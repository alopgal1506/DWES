class Animal () :
    def __init__(self, edad, peso, color):
        self.edad = edad
        self.peso = peso
        self.color=color
        
    def mostrarMarca(self) :
        return self.edad
    
    def mostrarModelo(self) :
        return self.peso
    
    def mostrarModelo(self) :
        return self.color
    
    def hablar(self) :
        return "Los animales no hablan"


